#!/usr/bin/env bash
set -Eeuo pipefail

# Usage: sudo TEMPLATE=/var/lib/libvirt/images/alma9-template.qcow2 ./create-lab.sh
# Requires: virsh, virt-install, qemu-img, cloud-localds, python3
# Template must be a generalized cloud-init-enabled AlmaLinux 9 image.

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
TOPOLOGY=${TOPOLOGY:-$SCRIPT_DIR/topology.csv}
TEMPLATE=${TEMPLATE:-/var/lib/libvirt/images/alma9-template.qcow2}
IMAGE_DIR=${IMAGE_DIR:-/var/lib/libvirt/images/openvox-lab}
OUTPUT_DIR=${OUTPUT_DIR:-$SCRIPT_DIR/generated}
DOMAIN=${DOMAIN:-lab.example}
NETWORK=${NETWORK:-default}
GATEWAY=${GATEWAY:-192.168.122.1}
PREFIX=${PREFIX:-24}
DNS=${DNS:-$GATEWAY}
SSH_PUBKEY=${SSH_PUBKEY:-${SUDO_USER:+/home/$SUDO_USER/.ssh/id_ed25519.pub}}
SSH_PUBKEY=${SSH_PUBKEY:-/root/.ssh/id_ed25519.pub}
START=${START:-0}
ONLY=""
REFRESH_SEEDS=0
while (($#)); do
  case "$1" in
    --only) [[ $# -ge 2 ]] || { echo '--only requires VM name' >&2; exit 2; }; ONLY=$2; shift 2 ;;
    --refresh-seeds) REFRESH_SEEDS=1; shift ;;
    -h|--help) echo 'Usage: create-lab.sh [--only VM] [--refresh-seeds]'; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

[[ $EUID -eq 0 ]] || { echo 'Run as root (sudo)' >&2; exit 1; }
for cmd in virsh virt-install qemu-img cloud-localds python3; do command -v "$cmd" >/dev/null || { echo "Missing command: $cmd" >&2; exit 1; }; done
[[ -f $TEMPLATE ]] || { echo "Missing template: $TEMPLATE" >&2; exit 1; }
[[ -f $TOPOLOGY ]] || { echo "Missing topology: $TOPOLOGY" >&2; exit 1; }
[[ -f $SSH_PUBKEY ]] || { echo "Missing SSH public key: $SSH_PUBKEY" >&2; exit 1; }
virsh net-info "$NETWORK" >/dev/null || { echo "Missing libvirt network: $NETWORK" >&2; exit 1; }
[[ $(virsh net-info "$NETWORK" | awk '/Active:/ {print $2}') == yes ]] || { echo "Libvirt network $NETWORK is not active" >&2; exit 1; }
mkdir -p "$IMAGE_DIR" "$OUTPUT_DIR/seeds"

# Fail early on invalid topology, duplicate names/IPs and unsafe characters.
python3 - "$TOPOLOGY" <<'PY'
import csv, ipaddress, re, sys
with open(sys.argv[1], newline='') as f: rows=list(csv.DictReader(f))
assert rows, 'Empty topology'
names=set(); ips=set()
for r in rows:
    assert re.fullmatch(r'[a-z][a-z0-9-]*',r['name']), r
    ipaddress.IPv4Address(r['ip'])
    assert r['name'] not in names and r['ip'] not in ips, 'Duplicate hostname/IP'
    names.add(r['name']); ips.add(r['ip'])
    assert int(r['ram_mb'])>=512 and int(r['vcpus'])>=1, r
PY
if [[ -n $ONLY ]] && ! awk -F, -v n="$ONLY" 'NR>1 && $1==n {found=1} END {exit !found}' "$TOPOLOGY"; then
  echo "Unknown VM in topology: $ONLY" >&2; exit 2
fi

INVENTORY="$OUTPUT_DIR/hosts.ini"
HOSTS="$OUTPUT_DIR/hosts.fragment"
printf '# Generated by create-lab.sh; do not edit manually\n' > "$INVENTORY"
printf '# OpenVox lab generated hosts\n' > "$HOSTS"
for role in postgresql haproxy openvox ca nfs; do
  printf '\n[%s]\n' "$role" >> "$INVENTORY"
  while IFS=, read -r name ip ram cpu item_role; do
    [[ $name == name || $item_role != "$role" ]] && continue
    printf '%s ansible_host=%s ansible_user=almalinux\n' "$name" "$ip" >> "$INVENTORY"
  done < "$TOPOLOGY"
done
printf '\n[all:vars]\nansible_python_interpreter=/usr/bin/python3\n' >> "$INVENTORY"

while IFS=, read -r name ip ram cpu role; do
  [[ $name == name ]] && continue
  [[ -n $ONLY && $name != "$ONLY" ]] && continue
  fqdn="$name.$DOMAIN"
  printf '%s %s %s\n' "$ip" "$fqdn" "$name" >> "$HOSTS"
  disk="$IMAGE_DIR/$name.qcow2"
  seed="$OUTPUT_DIR/seeds/$name-seed.iso"
  vm_seed_dir="$OUTPUT_DIR/seeds/$name"
  mkdir -p "$vm_seed_dir"
  existing=0
  if virsh dominfo "$name" >/dev/null 2>&1; then
    if [[ $REFRESH_SEEDS != 1 ]]; then
      echo "[SKIP] Domain exists: $name (use --refresh-seeds to update its seed while shut off)"
      continue
    fi
    [[ $(virsh domstate "$name" | tr -d '\r') == 'shut off' ]] || {
      echo "[ERROR] Shut down $name before refreshing its seed" >&2; exit 1;
    }
    existing=1
  fi
  if [[ $existing == 0 && -e $disk ]]; then
    echo "[ERROR] Disk exists but VM not defined: $disk (manual inspection required)" >&2
    exit 1
  fi
  if [[ $existing == 0 && -e $seed ]]; then
    echo "[ERROR] Seed exists but VM not defined: $seed" >&2
    exit 1
  fi
  if [[ $existing == 0 ]]; then
    qemu-img create -f qcow2 -F qcow2 -b "$(realpath "$TEMPLATE")" "$disk"
  fi
  python3 - "$fqdn" "$name" "$ip" "$PREFIX" "$GATEWAY" "$DNS" "$SSH_PUBKEY" "$vm_seed_dir" <<'PY'
import json, pathlib, sys
fqdn,name,ip,prefix,gateway,dns,pubkey,out=sys.argv[1:]
out=pathlib.Path(out)
key=pathlib.Path(pubkey).read_text().strip()
user_data = '#cloud-config\n' + '\n'.join([
    'hostname: '+name,
    'fqdn: '+fqdn,
    'manage_etc_hosts: true',
    'users:',
    '  - default',
    '  - name: almalinux',
    '    groups: [wheel]',
    '    sudo: "ALL=(ALL) NOPASSWD:ALL"',
    '    shell: /bin/bash',
    '    ssh_authorized_keys:',
    '      - '+json.dumps(key),
    'ssh_pwauth: false',
    'disable_root: true',
    'package_update: false',
    'runcmd:',
    '  - [hostnamectl, set-hostname, '+fqdn+']',
    # ISO-installed template retains an autoconnect DHCP profile for enp1s0.
    # Make cloud-init's static profile win, including on subsequent boots.
    '  - |',
    '    nmcli connection modify "System eth0" connection.interface-name enp1s0 connection.autoconnect yes connection.autoconnect-priority 100',
    '    nmcli -t -f NAME connection show | grep -Fxq enp1s0 && nmcli connection modify enp1s0 connection.autoconnect no || true',
    '    nmcli connection up "System eth0" ifname enp1s0',
])+'\n'

network = {
    'version': 2,
    'ethernets': {
        'eth0': {
            'match': {'name': 'en*'},
            'dhcp4': False,
            'addresses': [f'{ip}/{prefix}'],
            'routes': [
                {'to': '0.0.0.0/0', 'via': gateway}
            ],
            'nameservers': {
                'addresses': [dns]
            }
        }
    }
}

# Network config is YAML-compatible JSON; matches en* interfaces common for virtio on AlmaLinux.
(out/'user-data').write_text(user_data)
(out/'meta-data').write_text(f'instance-id: {fqdn}\nlocal-hostname: {fqdn}\n')
(out/'network-config').write_text(json.dumps(network,indent=2)+'\n')
PY
  tmp_seed="$seed.tmp"
  cloud-localds --network-config="$vm_seed_dir/network-config" "$tmp_seed" "$vm_seed_dir/user-data" "$vm_seed_dir/meta-data"
  mv -f "$tmp_seed" "$seed"
  if [[ $existing == 1 ]]; then
    echo "[REFRESHED SEED] $name (disk and domain unchanged)"
    continue
  fi
  virt-install --connect qemu:///system --name "$name" --memory "$ram" --vcpus "$cpu" \
    --import --os-variant almalinux9 --network "network=$NETWORK,model=virtio" \
    --disk "path=$disk,format=qcow2,bus=virtio" \
    --disk "path=$seed,device=cdrom" --graphics none --noautoconsole \
    --print-xml > "$vm_seed_dir/domain.xml"
  virsh define "$vm_seed_dir/domain.xml"
  echo "[CREATED] $name $ip ($role)"
  if [[ $START == 1 ]]; then virsh start "$name"; fi
done < "$TOPOLOGY"
echo "Inventory: $INVENTORY"
echo "Hosts fragment: $HOSTS"
echo 'CAUTION: Generated /etc/hosts fragment is not installed automatically.'
